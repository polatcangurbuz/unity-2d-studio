def parse(text, path):
    palette, sprites, section, current = {}, {}, None, None
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("# ") and not line.startswith("    "):
            continue
        indent = len(line) - len(line.lstrip())
        if indent == 0:
            section, current = line.rstrip(":").strip(), None
        elif section == "palette" and indent == 2:
            key, _, value = line.strip().partition(":")
            palette[key.strip()] = value.split()[0].strip("\"'") if value.split() else ""
        elif section == "sprites" and indent == 2:
            current = line.strip().split(":")[0].strip()
            sprites[current] = []
        elif section == "sprites" and current and indent >= 4:
            sprites[current].append(line.strip())
        else:
            sys.exit(f"{path}:{n}: cannot parse '{line.strip()}'")
    return palette, sprites


def rgba(value, roles, path):
    hex_code = value if value.startswith("#") else roles.get(value) or FALLBACK.get(value)
    if not hex_code or len(hex_code) != 7:
        sys.exit(f"{path}: palette value '{value}' is not a role ({', '.join(sorted(roles or FALLBACK))}) or #rrggbb")
    return tuple(int(hex_code[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def png(width, height, pixels):
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    rows = b"".join(b"\x00" + bytes(c for px in pixels[y * width:(y + 1) * width] for c in px) for y in range(height))
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b"")


def asset_name(key):
    return "SPR_" + "_".join(p[:1].upper() + p[1:] for p in key.replace(" ", "_").split("_") if p)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--force", action="store_true", help="overwrite existing PNGs")
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    spec = os.path.join(root, SPEC)
    if not os.path.exists(spec):
        os.makedirs(os.path.dirname(spec), exist_ok=True)
        open(spec, "w", encoding="utf-8", newline="\n").write(DEFAULT)
        print(f"wrote default {SPEC.replace(os.sep, '/')} (edit it and rerun with --force)")
    letters, sprites = parse(open(spec, encoding="utf-8").read(), spec)
    roles = read_palette(root)
    colors = {k: rgba(v, roles, spec) for k, v in letters.items()}
    colors["."] = (0, 0, 0, 0)
    out = os.path.join(root, OUT)
    os.makedirs(out, exist_ok=True)
    written, kept = [], []
    for key, rows in sprites.items():
        width = len(rows[0]) if rows else 0
        bad = [i for i, r in enumerate(rows, 1) if len(r) != width]
        unknown = sorted({c for r in rows for c in r} - set(colors))
        if not rows or bad or unknown:
            sys.exit(f"{spec}: sprite '{key}': " + (f"rows {bad} differ from width {width}" if bad else f"unknown letters {unknown}"))
        target = os.path.join(out, asset_name(key) + ".png")
        if os.path.exists(target) and not args.force:
            kept.append(os.path.basename(target))
            continue
        with open(target, "wb") as fh:
            fh.write(png(width, len(rows), [colors[c] for r in rows for c in r]))
        written.append(f"{os.path.basename(target)} {width}x{len(rows)}")
    source = "art bible" if roles else "fallback palette (no art bible yet)"
    print(f"{OUT.replace(os.sep, '/')}: wrote {', '.join(written) or '-'}; kept {', '.join(kept) or '-'}; colours: {source}")


if __name__ == "__main__":
    main()
